import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { composeCoverLetterDocument, formatCoverLetterBlocks, splitCoverLetterEnding } from "../src/lib/cover-letter-document";
import { generateCoverLetterHtml } from "../src/lib/cover-letter-renderer";

const letter = "Dear Hiring Manager,\n\nI build accessible applications.\n\nI would welcome a conversation about this role.\n\n**Sincerely,**\nAlex Example";

describe("clean cover-letter exports", () => {
    it("does not inject a date, watermark, document id, or product stamp", () => {
        const html = generateCoverLetterHtml(letter, "Application", { candidateName: "Alex Example" });
        assert.doesNotMatch(html, /class="date-section"|Generated by|Zebra AI|Document ID|Confidential|Applicant Name/);
        assert.doesNotMatch(html, /October|January|2026/);
    });

    it("preserves a date that the author wrote into the letter", () => {
        const html = generateCoverLetterHtml(`January 15, 2026\n\n${letter}`, "Application");
        assert.equal(html.split("January 15, 2026").length - 1, 1);
    });

    it("keeps the last body paragraph and existing Markdown closing together", () => {
        const blocks = formatCoverLetterBlocks(letter);
        const parts = splitCoverLetterEnding(blocks);
        assert.match(JSON.stringify(parts.ending), /welcome a conversation/);
        assert.match(JSON.stringify(parts.ending), /Sincerely/);
        assert.match(JSON.stringify(parts.ending), /Alex Example/);
        assert.doesNotMatch(JSON.stringify(parts.body), /Sincerely|welcome a conversation/);
        assert.deepEqual([...parts.body, ...parts.ending], blocks);
    });

    it("groups a generated closing with the final body paragraph", () => {
        const model = composeCoverLetterDocument("Dear Hiring Manager,\n\nMy experience fits this role.", { candidateName: "Alex Example" });
        const parts = splitCoverLetterEnding(model.blocks, Boolean(model.appendedClosing));
        assert.match(JSON.stringify(parts.ending), /experience fits/);
        assert.doesNotMatch(JSON.stringify(parts.ending), /Dear Hiring Manager/);
    });

    it("does not treat a salutation as the final body paragraph", () => {
        const parts = splitCoverLetterEnding(formatCoverLetterBlocks("Dear Hiring Manager,\n\nSincerely,\nAlex Example"));
        assert.doesNotMatch(JSON.stringify(parts.ending), /Dear Hiring Manager/);
    });

    it("renders the closing inside the pagination group without duplicating it", () => {
        const html = generateCoverLetterHtml(letter, "Application");
        assert.match(html, /class="cl-ending"/);
        assert.match(html, /break-inside:\s*avoid/);
        assert.match(html, /class="cl-ending">[\s\S]*welcome a conversation[\s\S]*Sincerely/);
        assert.equal(html.split("Sincerely").length - 1, 1);
    });
});

it("normalizes blank-line runs without changing letter text", () => {
    const normal = generateCoverLetterHtml("Dear Hiring Manager,\n\nMy experience fits this role.\n\nSincerely,\nAlex Example", "Application");
    const spaced = generateCoverLetterHtml("Dear Hiring Manager,\n\n\n\nMy experience fits this role.\n\n\nSincerely,\nAlex Example", "Application");
    assert.equal(spaced, normal);
});
